/**
 * Pinyin dictionaries for the Chinese G2P (Issue #829).
 *
 * The package ships `data/pinyin_single.json` and `data/pinyin_phrases.json`,
 * byte-identical copies of `src/rust/piper-plus-g2p/data/` (the dictionaries
 * the Rust `ChinesePhonemizer` reads; CI gate:
 * `scripts/check_dictionary_consistency.py` + `docs/spec/dictionary-mirrors.toml`).
 *
 * Together they are about 2.7 MB of JSON, so nothing here loads them at import
 * time: `loadPinyinDictionary()` imports them on first call (a dynamic JSON
 * module import, which works in Node and in browsers and lets bundlers split
 * the data into its own chunk) and keeps the result for the process.
 * `G2P.create()` calls it only when Chinese is enabled.
 *
 * Formats (generated by `scripts/build_pinyin_dicts.py`, tones as digits 1-5):
 * - single:  `{ "19968": "yi1,yi2,yi4", ... }` (decimal codepoint -> readings)
 * - phrases: `{ "一丁不识": [["yi1"], ["ding1"], ["bu4"], ["shi2"]], ... }`
 *
 * The parsed JSON objects are used as they are (no copy into a `Map`), and the
 * lookups below apply the same rules as Rust's `parse_single_char_json` /
 * `parse_phrase_json`: a single-character entry may be a string or an array
 * (first element), a phrase entry may be a space-separated string, an array of
 * strings, or an array of arrays (first element of each), and an entry that
 * yields nothing is treated as absent.
 *
 * @module zh/pinyin-dict
 */

/**
 * Pinyin dictionary pair used by `ChineseG2P`.
 */
export class PinyinDictionary {
  /**
   * @param {Record<string, unknown>} single  Parsed pinyin_single.json.
   * @param {Record<string, unknown>} phrases  Parsed pinyin_phrases.json.
   */
  constructor(single, phrases) {
    /** @private */
    this._single = single;
    /** @private */
    this._phrases = phrases;
  }

  /**
   * First reading of a single character, e.g. `"hao3"` for 好.
   *
   * @param {number} codepoint
   * @returns {string|null}
   */
  lookupChar(codepoint) {
    const key = String(codepoint);
    if (!Object.hasOwn(this._single, key)) {
      return null;
    }
    let raw = this._single[key];
    if (Array.isArray(raw)) {
      raw = raw[0];
    }
    if (typeof raw !== "string" || raw === "") {
      return null;
    }
    // Comma-separated alternatives: the first one is the reading.
    return raw.split(",")[0];
  }

  /**
   * Readings of a phrase, one per character, e.g. `["yin2", "hang2"]` for 银行.
   *
   * @param {string} phrase
   * @returns {string[]|null}
   */
  lookupPhrase(phrase) {
    if (!Object.hasOwn(this._phrases, phrase)) {
      return null;
    }
    const raw = this._phrases[phrase];
    /** @type {string[]} */
    let readings = [];
    if (typeof raw === "string") {
      readings = raw.split(/\s+/).filter((s) => s !== "");
    } else if (Array.isArray(raw)) {
      for (const item of raw) {
        if (typeof item === "string") {
          readings.push(item);
        } else if (Array.isArray(item) && typeof item[0] === "string") {
          readings.push(item[0]);
        }
      }
    }
    return readings.length > 0 ? readings : null;
  }
}

/**
 * @param {unknown} value
 * @param {string} name
 * @returns {Record<string, unknown>}
 */
function toJsonObject(value, name) {
  let parsed = value;
  if (typeof parsed === "string") {
    parsed = JSON.parse(parsed);
  } else if (parsed instanceof Uint8Array || parsed instanceof ArrayBuffer) {
    parsed = JSON.parse(new TextDecoder().decode(parsed));
  }
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new TypeError(`pinyinDict.${name} must be a JSON object (or its JSON text)`);
  }
  return /** @type {Record<string, unknown>} */ (parsed);
}

/**
 * Build a `PinyinDictionary` from dictionary data the caller loaded, for
 * example from a URL of its own. Each of `single` / `phrases` may be the
 * parsed JSON object, its JSON text, or its UTF-8 bytes. A `PinyinDictionary`
 * is returned as it is.
 *
 * @param {PinyinDictionary | { single: unknown, phrases: unknown }} data
 * @returns {PinyinDictionary}
 */
export function createPinyinDictionary(data) {
  if (data instanceof PinyinDictionary) {
    return data;
  }
  if (data === null || typeof data !== "object") {
    throw new TypeError("pinyinDict must be { single, phrases }");
  }
  return new PinyinDictionary(
    toJsonObject(data.single, "single"),
    toJsonObject(data.phrases, "phrases")
  );
}

/** @type {Promise<PinyinDictionary>|null} */
let bundledPromise = null;
/** @type {PinyinDictionary|null} */
let bundled = null;

/**
 * Load the pinyin dictionaries bundled with the package. The first call
 * imports the two JSON files; later calls return the same instance.
 *
 * @returns {Promise<PinyinDictionary>}
 */
export function loadPinyinDictionary() {
  if (!bundledPromise) {
    bundledPromise = Promise.all([
      import("../../data/pinyin_single.json", { with: { type: "json" } }),
      import("../../data/pinyin_phrases.json", { with: { type: "json" } }),
    ]).then(
      ([single, phrases]) => {
        bundled = createPinyinDictionary({ single: single.default, phrases: phrases.default });
        return bundled;
      },
      (err) => {
        // Let a later call try again (e.g. after a network error in a browser).
        bundledPromise = null;
        throw new Error(
          `@piper-plus/g2p: failed to load the bundled pinyin dictionaries ` +
            `(data/pinyin_single.json, data/pinyin_phrases.json): ${err?.message ?? err}. ` +
            `Pass pinyinDict to G2P.create() / ChineseG2P, or leave "zh" out of languages.`,
          { cause: err }
        );
      }
    );
  }
  return bundledPromise;
}

/**
 * Whether the bundled pinyin dictionaries have been loaded in this process.
 *
 * @returns {boolean}
 */
export function isPinyinDictionaryLoaded() {
  return bundled !== null;
}
